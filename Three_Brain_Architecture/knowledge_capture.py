#!/usr/bin/env python3

import json
from datetime import datetime, timezone
from pathlib import Path

BASE = Path("/home/destiny/Obsidian/Destiny/Three_Brain_Architecture")
KNOWLEDGE = Path("/home/destiny/Obsidian/Destiny/Knowledge_Base.md")
LOG = BASE / "Logs/knowledge_capture.json"


def capture(task, result):
    response = (
        result.get("model_response")
        or result.get("dl_result", {}).get("model_response", "")
    )

    if not response:
        return False

    # A PASS means the Three-Brain completed the task successfully.
    # It does NOT prove that every factual statement generated by the
    # language model is verified knowledge.
    if result.get("status") != "PASS":
        return False

    verified_facts = result.get("verified_facts")
    tool_result = result.get("tool_result")

    # Only promote a model response into the trusted Knowledge Base when
    # this task has real evidence attached to it.
    has_verified_facts = bool(verified_facts)
    has_tool_evidence = tool_result is not None

    if not has_verified_facts and not has_tool_evidence:
        return False

    evidence = {
        "verified_facts": verified_facts,
        "tool_result": tool_result,
    }

    entry = f"""
## {datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")}

**Task:** {task}

**Verified Result:**
{response}

**Verification Evidence:**
{json.dumps(evidence, indent=2)}

**Source:** Destiny Three-Brain Architecture

---
"""

    KNOWLEDGE.parent.mkdir(parents=True, exist_ok=True)

    with KNOWLEDGE.open("a", encoding="utf-8") as f:
        f.write(entry)

    history = []

    if LOG.exists():
        try:
            history = json.loads(LOG.read_text(encoding="utf-8"))
        except Exception:
            history = []

    history.append({
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "task": task,
        "status": "captured",
        "knowledge_file": str(KNOWLEDGE)
    })

    LOG.parent.mkdir(parents=True, exist_ok=True)
    LOG.write_text(json.dumps(history, indent=2), encoding="utf-8")

    return True
